"""Li child-process entry point. Never import this engine into a web worker.

Inputs and source bundles are supplied by a trusted backend executor. This
module performs no cloud writes and returns no result until artifact checks pass.
The parent owns process cancellation, resource limits, and publication.
"""
from copy import deepcopy
from hashlib import sha256
import json
from pathlib import Path
import sys

from packages.domain_bridge.planning_library import PlanningLibrary


ROOT = Path(__file__).resolve().parents[2]


def run(inputs, bundle, *, expected_version, output):
    """Execute in a fresh, parent-owned directory; reject reusable output paths."""
    if not isinstance(inputs, dict):
        raise ValueError('planning_input_invalid')
    # Li's CLI accepts an FX filename. Web jobs must carry actual JSON rates so
    # an input cannot access files or change meaning when a local file changes.
    if inputs.get('fx') is not None and not isinstance(inputs['fx'], dict):
        raise ValueError('planning_inline_fx_required')
    output = Path(output)
    if output.exists():
        raise ValueError('planning_output_already_exists')
    library = PlanningLibrary(bundle, expected_version=expected_version)
    sys.path.insert(0, str(ROOT / 'optimization' / 'tools'))
    import optimize
    from check import Checker

    optimizer = optimize.Optimizer(deepcopy(inputs), lib=library)
    before = optimizer.version()
    optimizer.run(output)
    checker = Checker(output, lib=library)
    failures = checker.run_all()
    if failures:
        raise ValueError('planning_artifact_checks_failed')
    after = checker.opt.version()
    for field in ('version_schema', 'inputs_sha256', 'rule_version',
                  'database_version', 'engine_sha256'):
        if before[field] != after[field]:
            raise ValueError('planning_runtime_changed')
    artifacts = {}
    total = 0
    for path in sorted(output.rglob('*')):
        if path.is_symlink():
            raise ValueError('planning_artifact_symlink')
        if not path.is_file():
            continue
        size = path.stat().st_size
        total += size
        if total > 50_000_000 or len(artifacts) >= 10000:
            raise ValueError('planning_artifact_limit')
        artifacts[path.relative_to(output).as_posix()] = {
            'bytes': size, 'sha256': sha256(path.read_bytes()).hexdigest()}
    return {'version': checker.version, 'artifacts': artifacts,
            'checks': {'status': 'passed', 'scope': 'li_checker_run_all'}}


def main():
    # Paths are generated by the backend parent, never supplied by HTTP clients.
    request_path, output, response = map(Path, sys.argv[1:])
    request = json.loads(request_path.read_text(encoding='utf-8'))
    result = run(request['input'], request['bundle'],
                 expected_version=request['library_snapshot'], output=output)
    response.write_text(json.dumps(result, ensure_ascii=False, allow_nan=False), encoding='utf-8')


if __name__ == '__main__':
    main()
